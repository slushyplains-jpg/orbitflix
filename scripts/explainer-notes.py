"""Regenerate a movie's clips.md footage log from script.txt and clips.json.

Usage: python3.11 explainer-notes.py <slug>
Keeps the log in step with the plan that is actually in the sheet.
"""
import json
import os
import re
import sys

slug = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
notes = os.path.join(root, "notes", "explainer", slug)
sents = re.split(r"(?<=[.!?])\s+", open(os.path.join(notes, "script.txt"), encoding="utf-8").read().strip())
clips = json.load(open(os.path.join(notes, "clips.json"), encoding="utf-8"))
mmss = lambda t: f"{int(t // 3600)}:{int(t % 3600 // 60):02d}:{t % 60:05.2f}" if t >= 3600 else f"{int(t // 60)}:{t % 60:05.2f}"
lines = [f"# {slug}: footage log", "", "Generated by scripts/explainer-notes.py from script.txt and clips.json. Do not edit by hand.", "",
         "| Clip | Sentences | Narration | Start | Subtitle at start | What the frame shows |", "|---|---|---|---|---|---|"]
for k, c in enumerate(clips, 1):
    a, b = c["sentences"]
    text = " ".join(sents[a:b + 1]).replace("|", "/")
    lines.append(f"| {k} | {a}-{b} | {text} | {mmss(c['start'])} | {c.get('quote', '') or '(none)'} | {c.get('action', '')} |")
open(os.path.join(notes, "clips.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"wrote {os.path.join(notes, 'clips.md')} ({len(clips)} clips)")
